/**
 * 전투력 가중치 — **표시 전용.**
 *
 * ⚠️ **이 값은 전투 결과에 어떤 영향도 주지 않는다.**
 * `battle.ts`·`encounter.ts`·`sim.ts`는 `power.ts`를 import하지 않는다.
 * 여기를 만져도 승률 표는 미동도 하지 않는다 — 바꿔 말하면 **여기를 만졌다고
 * `npm run sim`을 돌릴 필요가 없다.** 반대로 이 값이 엔진에 새어 들어가면
 * 밸런스 표가 조용히 낡는다. `power.test.ts`의 격리 테스트가 그것을 잠근다.
 *
 * ── 가중치를 어떻게 뽑았나 ─────────────────────────────
 * `deriveStats`(`stats.ts:64`)의 역산이다. 원시 스케일이 서로 다르다:
 *
 *   hp  = vit*20 + star*100     ← 네 자리
 *   atk = attr*6                ← 세 자리
 *   def = vit*2 + str
 *   spd = agi*3
 *   crit= 0.03 + agi*0.002      ← 0~0.6
 *
 * 그냥 더하면 **hp가 전투력의 90%를 먹는다.** 그래서 "능력치 1점이 만드는 기여"가
 * 서로 비슷해지도록 맞췄다:
 *
 *   vit 1점 → hp 20 × 0.30 = 6.0  (+ def 2 × 2.00 = 4.0)
 *   str 1점 → atk 6 × 1.00 = 6.0  (+ def 1 × 2.00 = 2.0)
 *   agi 1점 → spd 3 × 2.00 = 6.0
 *
 * crit는 상한 0.6(`stats.ts:71`에서 clamp)이라 600을 곱해도 최대 360 —
 * atk 스케일을 압도하지 않는다.
 */
export const POWER_WEIGHTS = {
  hp: 0.3,
  atk: 1.0,
  def: 2.0,
  spd: 2.0,
  crit: 600,
} as const;

