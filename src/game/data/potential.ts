/**
 * 잠재치 튜닝 파라미터.
 *
 * 흩어놓으면 튜닝이 불가능해지므로 전부 여기 모은다.
 * 이 값을 만졌으면 반드시 `npm run sim`으로 층별 승률을 확인할 것.
 */

export const POTENTIAL_TUNING = {
  /**
   * 현재치와 잠재치의 상관계수.
   *
   * 이 숫자 하나가 발굴의 재미를 단독으로 결정한다.
   *   1.0 → 보이는 게 전부. 발굴할 것이 없다.
   *   0.0 → 순수 도박. 판단이 개입할 여지가 없다.
   *   0.3 → 보이는 등급이 약한 신호. 유의미하지만 오해를 부른다. ← 여기가 재미있다
   */
  rho: 0.3,

  /**
   * sqrt(1 - rho²)를 미리 계산한 상수.
   * 런타임 sqrt를 쓰지 않는 이유는 결정론이다 (rng.ts의 rngNormal 주석 참조).
   * rho를 바꾸면 이 값도 같이 고쳐야 한다.
   */
  sqrtOneMinusRhoSq: 0.9539392,

  /**
   * 잠재 계수의 표준편차. 능력치 상한에 (1 + bonus)로 곱해진다.
   *
   * 0.08은 실측으로 정한 값이다. 6층 승률 스프레드가 파티 24종에서 이렇게 나왔다.
   *   sigma 0.18 →  0~99%   개체차가 파티 실력을 압도한다. 발굴이 재미가 아니라 강제가 된다.
   *   sigma 0.08 → 16~89%   개체차가 체감되면서 승패를 독점하지 않는다  ← 채택
   *   sigma 0.04 → 45~76%   너무 좁아 발굴할 가치가 안 생긴다
   *
   * 이 값을 올리려면 HANDOFF §5.1("보스 수치는 칼날이다")을 먼저 읽을 것.
   * 잠재치도 같은 칼날이다.
   */
  sigma: 0.08,

  /**
   * 계수 분포의 중심 이동. 기댓값이 0이면 안 되는 이유가 있다.
   *
   * 전투는 비선형이라 잠재치가 대칭으로 흔들려도 승률은 대칭으로 흔들리지 않는다.
   * 실측: 계수 -0.20이면 승률 4.8%, +0.20이면 100% (기준 78%) — 하락폭이 3배 이상 크다.
   * 한 명이 약해 일찍 죽으면 남은 인원의 피해가 누적돼 파티가 무너지지만,
   * 한 명이 강한 건 이미 이기던 전투를 더 빨리 이기는 것뿐이기 때문이다.
   *
   * 그래서 중심을 0에 두면 평균 승률이 70% → 52.7%로 주저앉는다.
   * +0.04에서 68.6%로 복원된다. 밸런스를 바꾸는 값이 아니라 지키는 값이다.
   */
  bias: 0.04,

  /**
   * 계수 하한/상한 (bias 적용 후 기준).
   * ±3σ에 bias를 더한 폭. 꼬리를 열어두되 밸런스가 깨지지 않는 선에서 자른다.
   */
  minBonus: -0.2,
  maxBonus: 0.28,
} as const;

/**
 * 발굴(reveal) 튜닝.
 * 진행도는 "써봐야 알 수 있다" — 전투에 내보내는 것 말고는 올릴 방법이 없다.
 */
export const REVEAL_TUNING = {
  /** 전투 1회 참여당 진행도 증가분 */
  perBattle: 0.06,
  /** 층 돌파 생존 시 추가 증가분 */
  perFloor: 0.1,
  /** 발굴 0%일 때의 추정 노이즈 폭 (잠재 계수 단위) */
  maxNoise: 0.35,
  /**
   * 발굴 100%에서도 남는 최소 구간 폭.
   *
   * 0이면 구간이 한 점으로 닫혀 "정확히 +0.193"이 되는데, 그건 스카우트 리포트가 아니라
   * 데이터 시트다. 좁히되 끝까지 재지는 못하게 남긴다.
   */
  minWidth: 0.012,
  /** 노이즈 감쇠 지수. 클수록 후반에 급격히 정확해진다. */
  noiseDecayK: 1.5,
  /**
   * 진행도 양자화 간격.
   *
   * 이게 없으면 진행도가 0.0001 움직일 때마다 추정치가 다시 뽑히고,
   * 화면이 깜빡이는 동시에 유저가 창을 여닫으며 추정치를 재추첨할 수 있다.
   */
  quantizeStep: 0.05,
} as const;
