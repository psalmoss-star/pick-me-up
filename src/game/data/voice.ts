/**
 * 대사 표 — 영웅이 말하는 다섯 순간. gdd-v3 §4.10.
 *
 * ── 왜 다섯 순간뿐인가 ──────────────────────────────────
 * **돌이킬 수 없는 결정의 앞뒤**에만 둔다: 불려 옴(소환) · 나섬(출정) ·
 * 바쳐짐(제물) · 남겨짐(동료 사망) · 떠남(죽음). 매 화면에 수다를 붙이면
 * 말이 배경 소음이 되고, 정작 유언의 무게가 사라진다.
 *
 * ── 자각 — 원작 재현 ────────────────────────────────────
 * 원작 '픽 미 업!'에서 영웅은 **등급이 높을수록 자기 처지를 잘 안다.**
 * - `low`(★1~3): 자기가 불려 왔다는 걸 모른다. 옛 세계의 말로 말한다.
 *   **마스터·탑·가챠라는 말을 쓰지 않는다**(테스트가 잠근다).
 * - `high`(★4~6): 탑과 마스터를 안다. 마스터에게 직접 말한다.
 *
 * ── 톤 ──────────────────────────────────────────────────
 * `names.ts`·`origins.ts`와 같다. 어둡고 건조하게, 짧게.
 * 기질은 **말투**로 드러나야지 설명으로 드러나면 안 된다 ("나는 충직하다" 금지).
 *
 * ── 자리표시 ────────────────────────────────────────────
 * `{ally}` — 동료 사망에서 먼저 간 동료의 이름. `{floor}` — 죽은 층.
 * 이름 뒤에 조사가 붙으면 **`{ally:이/가}`처럼 받침 있음/없음 두 꼴을 적는다.**
 * `{ally}가`로 적으면 「물결의 세인가」가 찍힌다(받침 있는 이름이 절반이다).
 * 쓸 수 있는 꼴: 이/가 · 을/를 · 은/는 · 이었/였. '의'·'도'처럼 안 바뀌는 조사는 그냥 붙인다.
 * 다른 자리표시를 쓰면 테스트가 실패한다(화면에 중괄호가 찍히는 사고를 막는다).
 *
 * ⚠️ 줄을 **추가**하는 것은 안전하지만 기존 개체가 그 순간에 하는 말이 바뀐다
 * (선택이 배열 길이에 의존한다). 무덤에 적힌 유언은 **저장된 문장**이라 안 바뀐다.
 */
